const dicts = { de, en };
let lang = 'de';
export function setLang(l) {
  lang = l === 'auto' ? ((navigator.language || 'de').toLowerCase().startsWith('de') ? 'de' : 'en') : l;
  document.documentElement.lang = lang;
}
export function getLang() { return lang; }
export function t(k, p) {
  let s = dicts[lang][k] ?? dicts.de[k] ?? k;
  if (p) for (const [a, b] of Object.entries(p)) s = s.replace('{' + a + '}', b);
  return s;
}
export function has(k) { return k in dicts[lang] || k in dicts.de; }
